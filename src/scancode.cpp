    std::optional<key_event> scancode::extract(scancode_queue::consumer_type* bytes, std::uint8_t set)
    {
        key k = key::bad_key;
        bool on = true;
        std::uint8_t ext = 0;
        static std::array<raw_scancode, 16> buf; // HACK
        std::size_t n = 0;

        for (auto i = bytes->cbegin(); i != bytes->cend(); ++i)
        {
            auto c = buf[n++] = *i;
            if (set <= 2 and (c & 0xF0) == 0xE0)
            {
                ext = c;
                continue;
            }
            if (set >= 2 and c == 0xF0)
            {
                on = false;
                continue;
            }

            bytes->pop_front_to(i + 1);

            switch (set)
            {
            case 1:
                on = not (c >> 7);
                c = set1_to_set2_table[c & 0x7f];
                [[fallthrough]];
            case 2:
                if (ext == 0xE0)
                {
                    if (c == 0x37) { k = key::pwr_on; break; }
                    if (c == 0x5E) { k = key::pwr_wake; break; }
                    if (auto p = set2_e0_to_set3_table[c]) { c = p; }
                    else { k = static_cast<key>(0xE000 | c); break; }
                }
                else if (ext == 0xE1)
                {
                    if (c == 0x14) { k = key::pause; break; }
                    else { k = static_cast<key>(0xE100 | c); break; }
                }
                else if (ext != 0) { k = static_cast<key>((ext << 8) | c); break; }
                else if (auto p = set2_to_set3_table[c]) { c = p; }
                [[fallthrough]];
            case 3:
                k = static_cast<key>(set3_to_key_table[c]);
                break;

            default:
                throw std::invalid_argument { "invalid scancode set" };
            }
            if (k == key::bad_key)
                k = static_cast<key>(0x0100 | c);

            return key_event
            {
                .key = k,
                .pressed = on,
                .repeat = false,
                .scancode_set = set,
                .scancode = { buf.data(), n }
            };
        }

        return std::nullopt;
    }
